package Array;
// Implementation of the array

public class Program1 {
    static void main(String[] args) {
        int[] arr = new int[5];
        arr[0] = 0;
        arr[1] = 1;
        arr[2] = 2;
        arr[3] = 3;
        arr[4] = 4;
        for (int j : arr) {
            System.out.print(j + " ");
        }
    }
}
